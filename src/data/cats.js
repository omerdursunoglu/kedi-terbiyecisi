export function pickRandomCatBreed(mapId, rng = Math.random) {
  // Boost city-themed cats slightly on their home map!
  const cityBonus = {
    istanbul: ['tekir', 'tombili', 'pasa', 'korsan'],
    antalya: ['portakal', 'sarman', 'calico'],
    tokat: ['yazmali', 'ankara', 'cayci'],
    artvin: ['yayla', 'van', 'poyraz', 'gokkusagi']
  };
  const favorites = cityBonus[mapId] || [];

  let total = 0;
  const weights = CAT_BREEDS.map((cat) => {
    const w = favorites.includes(cat.id) ? cat.weight * 1.65 : cat.weight;
    total += w;
    return w;
  });

  let roll = rng() * total;
  for (let i = 0; i < CAT_BREEDS.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return CAT_BREEDS[i];
  }
  return CAT_BREEDS[0];
}
